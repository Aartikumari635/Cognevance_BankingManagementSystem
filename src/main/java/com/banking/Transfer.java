    private void btnTransferActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTransferActionPerformed
        // TODO add your handling code here:
        


    String fromAccount = txtFromAccount.getText().trim();
    String toAccount = txtToAccount.getText().trim();
    String amountText = txtAmount.getText().trim();

    if (fromAccount.isEmpty() || toAccount.isEmpty()
            || amountText.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Please fill all required fields!");
        return;
    }

    if (fromAccount.equals(toAccount)) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Sender and receiver accounts must be different!");
        return;
    }

    java.math.BigDecimal amount;

    try {
        amount = new java.math.BigDecimal(amountText);

        if (amount.compareTo(java.math.BigDecimal.ZERO) <= 0) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Enter a valid transfer amount!");
            return;
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Enter a valid amount!");
        return;
    }

    java.sql.Connection con = null;

    try {
        con = DBConnection.getConnection();
        con.setAutoCommit(false);

        // Deduct money from sender only if balance is sufficient
        String debitSQL =
                "UPDATE accounts SET balance = balance - ? "
              + "WHERE account_number = ? AND balance >= ?";

        try (java.sql.PreparedStatement ps =
                con.prepareStatement(debitSQL)) {

            ps.setBigDecimal(1, amount);
            ps.setString(2, fromAccount);
            ps.setBigDecimal(3, amount);

            if (ps.executeUpdate() != 1) {
                con.rollback();
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Sender account not found or insufficient balance!");
                return;
            }
        }

        // Add money to receiver
        String creditSQL =
                "UPDATE accounts SET balance = balance + ? "
              + "WHERE account_number = ?";

        try (java.sql.PreparedStatement ps =
                con.prepareStatement(creditSQL)) {

            ps.setBigDecimal(1, amount);
            ps.setString(2, toAccount);

            if (ps.executeUpdate() != 1) {
                con.rollback();
                javax.swing.JOptionPane.showMessageDialog(
                        this, "Receiver account not found!");
                return;
            }
        }

  String historySQL =
    "INSERT INTO transactions " +
    "(sender_account, receiver_account, amount, status, transaction_type) " +
    "VALUES (?, ?, ?, ?, ?)";

try (java.sql.PreparedStatement ps =
        con.prepareStatement(historySQL)) {

    ps.setString(1, fromAccount);
    ps.setString(2, toAccount);
    ps.setBigDecimal(3, amount);
    ps.setString(4, "SUCCESS");
    ps.setString(5, "Transfer");

    ps.executeUpdate();
}

con.commit();


        con.commit();

        javax.swing.JOptionPane.showMessageDialog(
                this, "Money transferred successfully!\n"
                    + "Amount: ₹" + amount);

        txtAmount.setText("");

    } catch (Exception e) {
        if (con != null) {
            try {
                con.rollback();
            } catch (java.sql.SQLException ex) {
                e.addSuppressed(ex);
            }
        }

        javax.swing.JOptionPane.showMessageDialog(
                this, "Transfer failed: " + e.getMessage());

    } finally {
        if (con != null) {
            try {
                con.setAutoCommit(true);
                con.close();
            } catch (java.sql.SQLException e) {
                e.printStackTrace();
            }
        }
    }




    }//GEN-LAST:event_btnTransferActionPerformed

