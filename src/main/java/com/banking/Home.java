    private void btnDepositActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDepositActionPerformed
        // TODO add your handling code here:
        

    

    try {
        String accountNo = txtAccountNo.getText().trim();

        if (accountNo.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Please enter Account Number.");
            return;
        }

        String input = JOptionPane.showInputDialog(
                this, "Enter deposit amount:");

        if (input == null || input.trim().isEmpty()) {
            return;
        }

        java.math.BigDecimal amount =
                new java.math.BigDecimal(input.trim());

        if (amount.compareTo(java.math.BigDecimal.ZERO) <= 0) {
            JOptionPane.showMessageDialog(this,
                    "Amount must be greater than zero.");
            return;
        }

        try (java.sql.Connection con = DBConnection.getConnection()) {
            con.setAutoCommit(false);

            try {
                String sql = "UPDATE accounts "
                           + "SET balance = balance + ? "
                           + "WHERE account_number = ?";

                int rows;

                try (java.sql.PreparedStatement ps =
                        con.prepareStatement(sql)) {
                    ps.setBigDecimal(1, amount);
                    ps.setString(2, accountNo);
                    rows = ps.executeUpdate();
                }

                if (rows == 0) {
                    con.rollback();
                    JOptionPane.showMessageDialog(this,
                            "Account not found. Check Account Number.");
                    return;
                }

                String historySQL =
                        "INSERT INTO transactions "
                      + "(sender_account, receiver_account, amount, "
                      + "status, transaction_type) "
                      + "VALUES (?, NULL, ?, ?, ?)";

                try (java.sql.PreparedStatement ps =
                        con.prepareStatement(historySQL)) {
                    ps.setString(1, accountNo);
                    ps.setBigDecimal(2, amount);
                    ps.setString(3, "SUCCESS");
                    ps.setString(4, "Deposit");
                    ps.executeUpdate();
                    System.out.println("Deposit history inserted for account: " + accountNo);
                    System.out.println("Database: " + con.getCatalog());
                }

                con.commit();

                JOptionPane.showMessageDialog(this,
                        "Deposit Successful! Amount: ₹" + amount);

            } catch (java.sql.SQLException e) {
                con.rollback();
                throw e;
            }
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Please enter a valid amount.");
    } catch (java.sql.SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Database Error: " + e.getMessage());
    }


    


    }//GEN-LAST:event_btnDepositActionPerformed

