private void loadProfile() {
    String sql = "SELECT name, email ,phone FROM users WHERE user_id = ?";

    try (java.sql.Connection con = DBConnection.getConnection();
         java.sql.PreparedStatement ps = con.prepareStatement(sql)) {

        ps.setInt(1, userId);

        try (java.sql.ResultSet rs = ps.executeQuery()) {
            if (rs.next()) {
                txtname.setText(rs.getString("name"));
                txtemail.setText(rs.getString("email"));
                txtusername.setText(rs.getString("email"));
                txtphone.setText(rs.getString("phone"));

                // Mobile aur address database mein abhi available nahi hain
                txtphone.setText("");
                txtaddress.setText("");

                // Profile fields ko read-only rakhein
                txtname.setEditable(false);
                txtusername.setEditable(false);
                txtemail.setEditable(false);
                txtphone.setEditable(false);
                txtaddress.setEditable(false);
            } else {
                javax.swing.JOptionPane.showMessageDialog(
                    this, "User profile not found!");
            }
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Database error: " + e.getMessage());
    }
}

