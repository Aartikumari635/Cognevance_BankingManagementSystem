    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        // TODO add your handling code here:
        


    String name = txtCustomerName.getText().trim();
    String depositText = txtInitialDeposit.getText().trim();

    if (name.isEmpty() || depositText.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Please enter customer name and initial deposit!");
        return;
    }

    java.math.BigDecimal deposit;

    try {
        deposit = new java.math.BigDecimal(depositText);

        if (deposit.compareTo(java.math.BigDecimal.ZERO) <= 0) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Deposit must be greater than zero!");
            return;
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Enter a valid deposit amount!");
        return;
    }

    // Temporary user ID: replace with the logged-in user's actual ID.
    int userId = 1;

    // Generate a 12-digit account number.
    String accountNumber = "10"
        + java.util.UUID.randomUUID()
            .toString().replace("-", "").substring(0, 10);

    String sql = "INSERT INTO accounts "
        + "(user_id, account_number, balance) VALUES (?, ?, ?)";

    try (java.sql.Connection con = DBConnection.getConnection();
         java.sql.PreparedStatement ps = con.prepareStatement(sql)) {

        ps.setInt(1, userId);
        ps.setString(2, accountNumber);
        ps.setBigDecimal(3, deposit);

        int rows = ps.executeUpdate();

        
if (rows > 0) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Account created successfully!"
        + "\nCustomer: " + name
        + "\nAccount Number: " + accountNumber
        + "\nInitial Balance: ₹" + deposit
    );

   MyProfile profile = new MyProfile(userId);
profile.setLocationRelativeTo(null);
profile.setVisible(true);
this.dispose();
    
}


    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Database error: " + e.getMessage());
    }




    }//GEN-LAST:event_btnSubmitActionPerformed

