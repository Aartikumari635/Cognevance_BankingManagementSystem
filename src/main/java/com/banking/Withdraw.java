    private void btnWithdrawActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnWithdrawActionPerformed
        // TODO add your handling code here:
  

    String accountNo = txtAccountNo.getText().trim();
    String amountText = txtAmount.getText().trim();

    if (accountNo.isEmpty() || amountText.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Please enter account number and amount!");
        return;
    }

    java.math.BigDecimal amount;

    try {
        amount = new java.math.BigDecimal(amountText);

        if (amount.compareTo(java.math.BigDecimal.ZERO) <= 0) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Amount must be greater than zero!");
            return;
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Please enter a valid amount!");
        return;
    }

    String sql = "UPDATE accounts "
               + "SET balance = balance - ? "
               + "WHERE account_number = ? AND balance >= ?";

    try (java.sql.Connection con = DBConnection.getConnection();
         java.sql.PreparedStatement ps = con.prepareStatement(sql)) {

        ps.setBigDecimal(1, amount);
        ps.setString(2, accountNo);
        ps.setBigDecimal(3, amount);

        int rows = ps.executeUpdate();

        if (rows > 0) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Withdrawal Successful!\n"
                    + "Amount: ₹" + amount);

            txtAmount.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Account not found or insufficient balance!");
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Database Error: " + e.getMessage());
    }




    }//GEN-LAST:event_btnWithdrawActionPerformed

