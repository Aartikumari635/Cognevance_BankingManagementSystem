private void loadTransactions() {
    javax.swing.table.DefaultTableModel model =
        (javax.swing.table.DefaultTableModel) tblTransactions.getModel();

    model.setRowCount(0);

   
String sql = "SELECT transaction_id, transaction_date, " +
             "COALESCE(sender_account, receiver_account, '-') AS account_number, " +
             "COALESCE(transaction_type, 'Unknown') AS transaction_type, " +
             "amount, COALESCE(status, 'Unknown') AS status, " +
             "CONCAT('Type: ', COALESCE(transaction_type, 'Unknown'), " +
             " ' | Account: ', COALESCE(sender_account, receiver_account, '-')) AS description " +
             "FROM transactions ORDER BY transaction_id DESC";


    try (
        java.sql.Connection con = DBConnection.getConnection();
        java.sql.PreparedStatement ps = con.prepareStatement(sql);
        java.sql.ResultSet rs = ps.executeQuery()
    ) {
        
while (rs.next()) {
    model.addRow(new Object[] {
        rs.getInt("transaction_id"),
        rs.getTimestamp("transaction_date"),
        rs.getString("account_number"),
        rs.getString("transaction_type"),
        rs.getBigDecimal("amount"),
        rs.getString("status"),
        rs.getString("description")
    });
}

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Error: " + e.getMessage()
        );
    }
}

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
        

    String searchText = txtSearch.getText().trim().toLowerCase();
    String selectedType = cmbType.getSelectedItem().toString();

    javax.swing.table.TableRowSorter<javax.swing.table.TableModel> sorter =
        new javax.swing.table.TableRowSorter<>(tblTransactions.getModel());

    tblTransactions.setRowSorter(sorter);

    java.util.List<javax.swing.RowFilter<Object, Object>> filters =
        new java.util.ArrayList<>();

    if (!searchText.isEmpty()) {
        filters.add(javax.swing.RowFilter.regexFilter(
            "(?i)" + java.util.regex.Pattern.quote(searchText)
        ));
    }

    if (!selectedType.equals("All")) {
        filters.add(javax.swing.RowFilter.regexFilter(
            "^" + java.util.regex.Pattern.quote(selectedType) + "$", 3
        ));
    }

    sorter.setRowFilter(
        javax.swing.RowFilter.andFilter(filters)
    );


    }//GEN-LAST:event_btnSearchActionPerformed

